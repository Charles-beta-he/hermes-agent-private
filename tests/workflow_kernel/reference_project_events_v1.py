def _status_after_event(status: str, event: Mapping[str, Any]) -> str:
    event_type = event["event_type"]
    if event_type == "claimed":
        return "claimed"
    if event_type == "intent_recorded":
        return "intent_recorded"
    if event_type == "observation_recorded":
        payload = event["payload"]
        obs = payload.get("observation")
        classification = None
        if isinstance(obs, dict):
            classification = obs.get("classification")
        else:
            classification = payload.get("classification")
        if classification == "unknown":
            return "unknown"
        return "observed"
    if event_type == "reconciled":
        return "reconciled"
    if event_type == "receipt_terminal":
        payload = event["payload"]
        rc = payload.get("result_classification")
        if rc is None and isinstance(payload.get("receipt"), dict):
            rc = payload["receipt"].get("result_classification")
        if rc == "not_applied":
            return "not_applied"
        return "applied"
    if event_type == "compensation_intent":
        return "compensation_pending"
    if event_type == "compensation_observation":
        return "compensation_observed"
    if event_type == "compensation_receipt":
        return "compensated"
    raise ValueError(f"unsupported event_type: {event_type}")


def _fact_digest(value: object) -> str:
    return canonical_digest_v1(thaw_admitted_json_v1(value))


def _independent_receipt_public_v1(receipt: Mapping[str, Any]) -> dict[str, Any]:
    """Extract receipt public fields from protocol literals (no production parser)."""
    assert isinstance(receipt, Mapping)
    missing = [k for k in RECEIPT_PUBLIC_KEYS_V1 if k not in receipt]
    if missing:
        raise AssertionError(f"receipt missing protocol keys: {missing}")
    target = receipt["target"]
    assert isinstance(target, Mapping)
    assert set(target) == {"target_kind", "target_ref"}
    out = {
        "schema_version": receipt["schema_version"],
        "effect_id": receipt["effect_id"],
        "command_digest": receipt["command_digest"],
        "adapter_id": receipt["adapter_id"],
        "operation": receipt["operation"],
        "target": {
            "target_kind": target["target_kind"],
            "target_ref": target["target_ref"],
        },
        "payload_digest": receipt["payload_digest"],
        "authority_binding_digest": receipt["authority_binding_digest"],
        "idempotency_key": receipt["idempotency_key"],
        "fence": receipt["fence"],
        "preflight_readback": deepcopy(thaw_admitted_json_v1(receipt["preflight_readback"])),
        "post_readback": deepcopy(thaw_admitted_json_v1(receipt["post_readback"])),
        "result_classification": receipt["result_classification"],
        "compensation_ref": receipt["compensation_ref"],
        "reconcile_ref": receipt["reconcile_ref"],
        "receipt_digest": receipt["receipt_digest"],
    }
    assert set(out) == set(RECEIPT_PUBLIC_KEYS_V1)
    return out



def reference_idempotency_documents_from_events_v1(
    events: Sequence[Mapping[str, Any]],
) -> dict[str, dict[str, Any]]:
    """Independently construct exact full-identity idempotency index documents from events.

    Protocol rule (mirrors durable index owner, not SUT projection):
    - claimed binds under payload.idempotency_key (command key)
    - all later events bind under envelope idempotency_key
    - full first-claim identity fields come from the event payload
    - state is bound; event_id is the durable event id
    """
    docs: dict[str, dict[str, Any]] = {}
    for event in events:
        payload = event["payload"]
        event_type = event["event_type"]
        if event_type == "claimed":
            key = str(payload["idempotency_key"])
        else:
            key = str(event["idempotency_key"])
        required = (
            "request_digest",
            "target_digest",
            "command_digest",
            "adapter_id",
            "operation",
            "payload_digest",
            "fence",
        )
        missing = [k for k in required if payload.get(k) is None]
        if missing:
            raise AssertionError(
                f"event {event_type} missing identity fields for index construction: {missing}"
            )
        docs[key] = {
            "schema_version": "workflow_effect_idempotency_index_v1",
            "state": "bound",
            "request_digest": payload["request_digest"],
            "effect_id": str(event["effect_id"]),
            "target_digest": payload["target_digest"],
            "idempotency_key": key,
            "event_id": str(event["event_id"]),
            "fence": payload["fence"],
            "command_digest": payload["command_digest"],
            "adapter_id": payload["adapter_id"],
            "operation": payload["operation"],
            "payload_digest": payload["payload_digest"],
        }
    return docs


def reference_project_events_v1(events: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Reduce fixture events into combined public+durable reference shape."""
    plain_events = [thaw_admitted_json_v1(deepcopy(dict(e))) for e in events]
    assert all(isinstance(e, dict) for e in plain_events)

    if not plain_events:
        return deepcopy(REFERENCE_KNOWN_VECTOR_SNAPSHOTS_V1["empty"])

    effect_id = plain_events[0]["effect_id"]
    fence = None
    terminal_receipt_digest = None
    terminal_receipt = None
    observation = None
    facts: dict[str, Any] = {}
    idempotency_index: dict[str, str] = {}

    for event in plain_events:
        payload = event["payload"]
        event_type = event["event_type"]
        idempotency_index[str(event["idempotency_key"])] = str(event["event_id"])
        if event_type == "claimed":
            fence = payload.get("fence")
            facts["owner"] = payload.get("owner")
            facts["request_digest"] = payload.get("request_digest")
            facts["command_digest"] = payload.get("command_digest")
            facts["target_digest"] = payload.get("target_digest")
            facts["idempotency_key"] = payload.get("idempotency_key")
            facts["adapter_id"] = payload.get("adapter_id")
            facts["operation"] = payload.get("operation")
            facts["payload_digest"] = payload.get("payload_digest")
            facts["effect_id"] = event.get("effect_id")
            facts["fence"] = payload.get("fence")
        elif event_type == "intent_recorded":
            facts["authority_binding_digest"] = payload.get("authority_binding_digest")
            facts["preflight_readback"] = payload.get("preflight_readback")
            facts["preflight_readback_digest"] = payload.get("preflight_readback_digest")
        elif event_type == "observation_recorded":
            obs = payload.get("observation")
            if isinstance(obs, dict):
                observation = obs
                facts["classification"] = obs.get("classification")
                facts["readback"] = obs.get("readback")
                facts["observation"] = obs
            else:
                facts["classification"] = payload.get("classification")
                facts["readback"] = payload.get("readback")
                observation = {
                    "classification": payload.get("classification"),
                    "adapter_result_digest": payload.get("adapter_result_digest"),
                    "readback": payload.get("readback"),
                    "fence": payload.get("fence"),
                }
            if "readback_digest" in payload:
                facts["readback_digest"] = payload.get("readback_digest")
            elif facts.get("readback") is not None:
                facts["readback_digest"] = _fact_digest(facts["readback"])
        elif event_type == "reconciled":
            facts["reconcile_classification"] = payload.get("classification")
            facts["readback"] = payload.get("readback")
            if "readback_digest" in payload:
                facts["readback_digest"] = payload.get("readback_digest")
            elif facts.get("readback") is not None:
                facts["readback_digest"] = _fact_digest(facts["readback"])
            facts["reconcile_readback"] = facts.get("readback")
            facts["reconcile_readback_digest"] = facts.get("readback_digest")
            facts["reconcile"] = dict(payload)
        elif event_type == "receipt_terminal":
            receipt = payload.get("receipt")
            if isinstance(receipt, dict):
                terminal_receipt = _independent_receipt_public_v1(receipt)
                terminal_receipt_digest = terminal_receipt["receipt_digest"]
                facts["result_classification"] = terminal_receipt["result_classification"]
                facts["terminal_receipt"] = terminal_receipt
            else:
                terminal_receipt_digest = payload.get("receipt_digest")
                facts["result_classification"] = payload.get("result_classification")
        elif event_type == "compensation_intent":
            facts["compensation_request_digest"] = payload.get("request_digest")
            facts["compensation_command_digest"] = payload.get("command_digest")
            facts["compensation_target_digest"] = payload.get("target_digest")
            facts["compensation_payload_digest"] = payload.get("payload_digest")
            facts["compensation_authority_binding_digest"] = payload.get(
                "authority_binding_digest"
            )
            facts["compensation_adapter_id"] = payload.get("adapter_id")
            facts["compensation_operation"] = payload.get("operation")
            facts["compensation_idempotency_key"] = payload.get("idempotency_key")
            facts["compensation_effect_id"] = payload.get("effect_id")
            facts["compensation_fence"] = payload.get("fence")
            facts["compensation_ref"] = payload.get("compensation_ref")
            facts["original_receipt_digest"] = payload.get("original_receipt_digest")
            facts["original_receipt"] = payload.get("original_receipt")
            facts["compensation_preflight_readback"] = payload.get("preflight_readback")
            facts["compensation_preflight_readback_digest"] = payload.get(
                "preflight_readback_digest"
            )
            facts["compensation_intent"] = dict(payload)
        elif event_type == "compensation_observation":
            obs = payload.get("observation")
            if isinstance(obs, dict):
                facts["compensation_observation"] = obs
                facts["compensation_classification"] = obs.get("classification")
                facts["compensation_readback"] = obs.get("readback")
            else:
                facts["compensation_classification"] = payload.get("classification")
                facts["compensation_readback"] = payload.get("readback")
            if "readback_digest" in payload:
                facts["compensation_readback_digest"] = payload.get("readback_digest")
            elif facts.get("compensation_readback") is not None:
                facts["compensation_readback_digest"] = _fact_digest(
                    facts["compensation_readback"]
                )
            for key in (
                "request_digest",
                "command_digest",
                "target_digest",
                "payload_digest",
                "authority_binding_digest",
                "adapter_id",
                "operation",
                "idempotency_key",
                "fence",
            ):
                if f"compensation_{key}" not in facts and key in payload:
                    facts[f"compensation_{key}"] = payload.get(key)
            if "original_receipt_digest" in payload:
                facts["original_receipt_digest"] = payload.get("original_receipt_digest")
            if "original_receipt" in payload:
                facts["original_receipt"] = payload.get("original_receipt")
        elif event_type == "compensation_receipt":
            # Status transitions to compensated; facts retain prior compensation chain.
            pass

    status = "absent"
    for event in plain_events:
        status = _status_after_event(status, event)

    # Publicize intent_recorded → unknown (awaiting reconcile), matching public API.
    if status == "intent_recorded":
        status = "unknown"
        facts = {
            **facts,
            "awaiting_reconcile": True,
            "durable_phase": "intent_recorded",
        }

    tip = plain_events[-1]
    index_documents = reference_idempotency_documents_from_events_v1(plain_events)
    return {
        "effect_id": effect_id,
        "status": status,
        "fence": fence,
        "facts": facts,
        "terminal_receipt_digest": terminal_receipt_digest,
        "terminal_receipt": terminal_receipt,
        "observation": observation,
        "event_count": len(plain_events),
        "sequence": int(tip["sequence"]),
        "tip_event_id": str(tip["event_id"]),
        "idempotency_index": {k: str(v["event_id"]) for k, v in index_documents.items()},
        "idempotency_index_documents": index_documents,
    }


def split_reference_projection_v1(proj: Mapping[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
    """Split combined reference into exact public object + durable evidence object."""
    public = {k: deepcopy(proj[k]) for k in sorted(PUBLIC_PROJECTION_KEYS_V1)}
    durable = {k: deepcopy(proj[k]) for k in sorted(DURABLE_EVIDENCE_KEYS_V1) if k in proj}
    # Ensure durable always has required keys.
    for k in DURABLE_EVIDENCE_KEYS_V1:
        durable.setdefault(k, {} if k.endswith("documents") or k == "idempotency_index" else None)
