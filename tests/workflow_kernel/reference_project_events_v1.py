def assert_reference_known_vectors() -> None:
    """Execute every major-status hand-authored sequence against the reducer with full equality."""
    required = {
        "empty",
        "claimed",
        "claimed_only",
        "intent_recorded",
        "unknown_observed",
        "observed",
        "reconciled",
        "receipt_terminal_applied",
        "receipt_terminal_not_applied",
        "compensation_intent",
        "compensation_observed",
        "compensation_receipt_terminal",
        "compensation_reconciled",
    }
    assert required <= set(REFERENCE_KNOWN_VECTOR_SNAPSHOTS_V1)
    assert required <= set(REFERENCE_KNOWN_VECTOR_SEQUENCES_V1)
    # No snapshot may be a shared object alias of another.
    ids = {n: id(REFERENCE_KNOWN_VECTOR_SNAPSHOTS_V1[n]) for n in required}
    if len(set(ids.values())) != len(ids):
        raise AssertionError(f"snapshot object aliasing detected: {ids}")

    for name in sorted(REFERENCE_KNOWN_VECTOR_SEQUENCES_V1):
        seq = REFERENCE_KNOWN_VECTOR_SEQUENCES_V1[name]
        expected = REFERENCE_KNOWN_VECTOR_SNAPSHOTS_V1[name]
        got = reference_project_events_v1(seq)
        if got != expected:
            raise AssertionError(
                f"reference vector mismatch for {name}: got={got!r} expected={expected!r}"
            )
        assert set(expected) == set(REFERENCE_COMBINED_KEYS_V1), name
        public, durable = split_reference_projection_v1(expected)
        assert set(public) == set(PUBLIC_PROJECTION_KEYS_V1), name
        assert set(durable) == set(DURABLE_EVIDENCE_KEYS_V1), name

    # Status coverage across hardcoded vectors (major states).
    statuses = {
        REFERENCE_KNOWN_VECTOR_SNAPSHOTS_V1[n]["status"]
        for n in required
    }
    for need in {
        "absent",
        "claimed",
        "unknown",
        "observed",
        "reconciled",
        "applied",
        "not_applied",
        "compensation_pending",
        "compensation_observed",
        "compensated",
    }:
        assert need in statuses, need


def materialize_vector_through_sut_public_api_v1(tmp_root, events):
    """Materialize sequence via WorkflowEffectLedger public claim/append API; return public projection.

    Empty sequence must call the actual public absence API on an isolated empty ledger.
    """
    from pathlib import Path
    from workflow_kernel import workflow_effect_ledger as ledger
    from workflow_kernel.effect_contracts import thaw_admitted_json_v1

    root = Path(tmp_root)
    root.mkdir(parents=True, exist_ok=True)
    if not events:
        # Isolated empty ledger: public absence projection for the literal empty-vector effect id.
        return thaw_admitted_json_v1(
            ledger.project_effect_v1(private_root=root, effect_id=EMPTY_VECTOR_EFFECT_ID_V1)
        )
    first = events[0]
    if first["event_type"] != "claimed":
        raise AssertionError("vector must start with claimed for public materialization")
    ledger.claim_effect_v1(
        private_root=root,
        effect_id=str(first["effect_id"]),
        payload=dict(first["payload"]),
        idempotency_key=str(first["idempotency_key"]),
        occurred_at=str(first["occurred_at"]),
    )
    for ev in events[1:]:
        ledger.append_effect_event_v1(
            private_root=root,
            effect_id=str(ev["effect_id"]),
            event_type=str(ev["event_type"]),
            payload=dict(ev["payload"]),
            idempotency_key=str(ev["idempotency_key"]),
            occurred_at=str(ev["occurred_at"]),
        )
    return thaw_admitted_json_v1(
        ledger.project_effect_v1(private_root=root, effect_id=str(first["effect_id"]))
    )


def assert_reference_and_sut_known_vectors(tmp_path_factory=None) -> None:
    """Reference reducer exact-equals literal snapshots; SUT public projection full-equality."""
    import tempfile
    from pathlib import Path

    assert_reference_known_vectors()
    for name in sorted(REFERENCE_KNOWN_VECTOR_SEQUENCES_V1):
        seq = REFERENCE_KNOWN_VECTOR_SEQUENCES_V1[name]
        expected = REFERENCE_KNOWN_VECTOR_SNAPSHOTS_V1[name]
        public_expected, _ = split_reference_projection_v1(expected)
        if set(public_expected) != set(PUBLIC_PROJECTION_KEYS_V1):
            raise AssertionError(
                f"literal public_expected keys != PUBLIC_PROJECTION_KEYS_V1 for {name}"
            )
        td = Path(tempfile.mkdtemp(prefix=f"vec_{name}_"))
        try:
            sut_projection = materialize_vector_through_sut_public_api_v1(td, seq)
            if set(sut_projection) != set(PUBLIC_PROJECTION_KEYS_V1):
                raise AssertionError(
                    f"SUT key set != PUBLIC_PROJECTION_KEYS_V1 vector={name} "
                    f"sut={sorted(sut_projection)} public={sorted(PUBLIC_PROJECTION_KEYS_V1)}"
                )
            if sut_projection != public_expected:
                raise AssertionError(
                    f"SUT full public inequality vector={name} "
                    f"sut={sut_projection!r} expected={public_expected!r}"
                )
        finally:
            import shutil
            shutil.rmtree(td, ignore_errors=True)


